import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  buildConsumerFromConfig,
  bundleConsumerServer,
  createWorkDirectory,
  installPackedSdk,
  linkDeclaredDependencies,
  repoRoot,
  type PackedSdk,
  type SdkPackage,
} from './packed-consumer.js';

// Qualification build of examples/tic-tac-toe, the way an application outside this repository
// would receive SAGA: the example is copied into a clean directory, the SDK packages are installed
// into it from packed candidate tarballs (no registry), and the example's own scripts and
// configuration build it (see packed-consumer.ts). The example was generated by the React/Hono
// `saga init` and keeps the template's build files, so this reuses the starter's machinery and adds
// no build of its own.
//
//   npx tsx scripts/build-tic-tac-toe.ts   # writes apps/lit-host/dist/tic-tac-toe, and tic-tac-toe-guided with the guide's change applied (ignored)
//
// Building the candidate is not publishing anything.

export const ticTacToeSource = path.join(repoRoot, 'examples', 'tic-tac-toe');
export const ticTacToeDist = path.join(
  repoRoot,
  'apps',
  'lit-host',
  'dist',
  'tic-tac-toe',
);

/** The SDK packages the example installs: the five the React/Hono template names. */
export const TIC_TAC_TOE_SDK_PACKAGES: readonly SdkPackage[] = [
  'core',
  'react',
  'components',
  'mcp',
  'react-mcp-stack',
];

/**
 * What the qualification harness adds around the example, outside its source: the entry through
 * which a test starts the listener with a store of its own.
 */
const QUALIFICATION_ENTRY = `export { startListener } from './server/listener.js';
export { createMemoryGameStore } from './server/game-store.js';
export { ViewArtifactMissing } from './server/operations.js';
export { VIEW_MARKER } from './src/contract.js';
`;

export interface PreparedTicTacToe {
  readonly consumer: string;
  readonly sdk: PackedSdk;
}

/** Everything a package manager would put beside the example, except what it declares nowhere. */
function declaredThirdParty(consumer: string): string[] {
  const manifest = JSON.parse(
    fs.readFileSync(path.join(consumer, 'package.json'), 'utf8'),
  ) as {
    dependencies?: Record<string, string>;
    devDependencies?: Record<string, string>;
  };
  return Object.keys({
    ...manifest.dependencies,
    ...manifest.devDependencies,
  }).filter((name) => !name.startsWith('@saga-a2ui/'));
}

/** The guided change of the tic-tac-toe guide: a patch to the layout and the catalog that adds a move list. */
export const ticTacToeGuidedChange = path.join(
  ticTacToeSource,
  'guided-change',
  'move-list.patch',
);

/** Where the browser specification reads the page built with the guided change applied. */
export const ticTacToeGuidedDist = path.join(
  repoRoot,
  'apps',
  'lit-host',
  'dist',
  'tic-tac-toe-guided',
);

export interface PrepareOptions {
  /** Applies `guided-change/move-list.patch` to the copy, as a reader of the guide does. */
  readonly guidedChange?: boolean;
}

/** Copies the example source into `work` and installs the packed SDK packages beside it. */
export function prepareTicTacToe(
  work: string,
  options: PrepareOptions = {},
): PreparedTicTacToe {
  const consumer = path.join(work, 'tic-tac-toe');
  fs.mkdirSync(consumer);
  const sdk = installPackedSdk(work, consumer, [...TIC_TAC_TOE_SDK_PACKAGES]);
  fs.cpSync(ticTacToeSource, consumer, {
    recursive: true,
    filter: (from) => !/(^|[\\/])(node_modules|dist)([\\/]|$)/.test(from),
  });
  if (options.guidedChange)
    // `git apply` works in a directory that is not a repository: the patch names src/ files.
    execFileSync(
      'git',
      ['apply', '--whitespace=nowarn', ticTacToeGuidedChange],
      {
        cwd: consumer,
      },
    );
  linkDeclaredDependencies(consumer, sdk, declaredThirdParty(consumer));
  return { consumer, sdk };
}

/** Type-checks the example with the compiler it declares, the way `npm run typecheck` does. */
export function typecheckTicTacToe(consumer: string): void {
  const tsc = path.join(consumer, 'node_modules', 'typescript', 'bin', 'tsc');
  for (const project of ['tsconfig.json', 'tsconfig.server.json'])
    execFileSync(process.execPath, [tsc, '-p', path.join(consumer, project)], {
      cwd: consumer,
      stdio: 'pipe',
    });
}

export interface BuiltTicTacToe extends PreparedTicTacToe {
  /** The one self-contained page, as the example's own `build:view` writes it. */
  readonly view: string;
  /** The example's own server bundle (`build:server`), whose entry is `server/main.ts`. */
  readonly server: string;
  /** The server bundle with the qualification entry, which lets a test choose the store. */
  readonly qualificationServer: string;
  /** Every module of the view's build graph. */
  readonly viewModules: readonly string[];
}

/** Builds the example with its own Vite configuration files, then adds the qualification bundle. */
export async function buildTicTacToe(
  prepared: PreparedTicTacToe,
): Promise<BuiltTicTacToe> {
  const { consumer } = prepared;
  const viewModules = await buildConsumerFromConfig(consumer, 'vite.config.ts');
  await buildConsumerFromConfig(consumer, 'vite.server.config.ts');
  fs.writeFileSync(
    path.join(consumer, 'qualification-entry.ts'),
    QUALIFICATION_ENTRY,
  );
  const qualification = await bundleConsumerServer(
    consumer,
    'qualification-entry.ts',
  );
  const view = path.join(consumer, 'dist', 'index.html');
  const server = path.join(consumer, 'dist', 'server.mjs');
  for (const file of [view, server])
    if (!fs.existsSync(file))
      throw new Error(
        `The example's build did not write ${path.relative(consumer, file)}.`,
      );
  return {
    ...prepared,
    view,
    server,
    qualificationServer: qualification.file,
    viewModules,
  };
}

const sha256 = (file: string): string =>
  createHash('sha256').update(fs.readFileSync(file)).digest('hex');

/** Builds the example into `outDir` for the browser specification and returns the identities a review needs. */
export async function buildTicTacToeInto(
  outDir: string,
  options: PrepareOptions = {},
): Promise<Record<string, unknown>> {
  const work = createWorkDirectory('saga-tic-tac-toe-');
  try {
    const prepared = prepareTicTacToe(work, options);
    typecheckTicTacToe(prepared.consumer);
    const built = await buildTicTacToe(prepared);
    fs.rmSync(outDir, { recursive: true, force: true });
    fs.mkdirSync(outDir, { recursive: true });
    // The example's own server and page, side by side as its `npm start` expects them: running
    // `node server.mjs` from this directory serves the game.
    fs.copyFileSync(built.view, path.join(outDir, 'index.html'));
    fs.copyFileSync(built.server, path.join(outDir, 'server.mjs'));
    fs.copyFileSync(
      built.qualificationServer,
      path.join(outDir, 'qualification-server.mjs'),
    );
    return {
      sourceCommit: execFileSync('git', ['rev-parse', 'HEAD'], {
        cwd: repoRoot,
        encoding: 'utf8',
      }).trim(),
      sourceDirty:
        execFileSync(
          'git',
          ['status', '--porcelain=v1', '--untracked-files=no'],
          { cwd: repoRoot, encoding: 'utf8' },
        ).trim() !== '',
      platform: `${process.platform}-${process.arch}`,
      node: process.version,
      installedPackages: Object.keys(built.sdk.manifests).sort(),
      packedTarballSha256: built.sdk.tarballSha256,
      builtView: { sha256: sha256(built.view) },
      builtServer: { sha256: sha256(built.server) },
      source: path.relative(repoRoot, ticTacToeSource),
    };
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

if (
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  for (const [outDir, options] of [
    [ticTacToeDist, {}],
    [ticTacToeGuidedDist, { guidedChange: true }],
  ] as const) {
    const identity = await buildTicTacToeInto(outDir, options);
    fs.writeFileSync(
      path.join(outDir, 'identity.json'),
      `${JSON.stringify(identity, null, 2)}\n`,
    );
    console.log(JSON.stringify(identity, null, 2));
  }
}
